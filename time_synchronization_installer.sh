# ---------------------------------------------------------------------------
# Reading the generated files.  The values contain spaces ("-f a -f b"), so the
# file must NOT be sourced as shell; pull out the single line we want instead.
# Deliberately no pipe: under `set -o pipefail`, sed taking SIGPIPE from a
# `head -n1` would make the assignment itself fail under `set -e` and abort.
# ---------------------------------------------------------------------------
env_get() {  # env_get KEY -> value on stdout; exit 1 if unset or empty
  local v=""
  [ -r "$(R "$ENV_FILE")" ] || return 1
  v="$(sed -n "s/^$1=//p" "$(R "$ENV_FILE")")"
  v="${v%%$'\n'*}"
  [ -n "$v" ] || return 1
  printf '%s\n' "$v"
}

state_get() {  # state_get KEY -> value on stdout; exit 1 if absent
  local v=""
  [ -r "$(R "$STATE_FILE")" ] || return 1
  v="$(sed -n "s/^$1=//p" "$(R "$STATE_FILE")")"
  v="${v%%$'\n'*}"
  [ -n "$v" ] || return 1
  printf '%s\n' "$v"
}

conf_get() {  # conf_get CONF_PATH KEY -> value on stdout; exit 1 if absent
  local v=""
  [ -r "$(R "$1")" ] || return 1
  v="$(sed -n "s/^$2[[:space:]]*//p" "$(R "$1")")"
  v="${v%%$'\n'*}"
  [ -n "$v" ] || return 1
  printf '%s\n' "$v"
}

# Which clock this board's ptp4l stamps in.  The flag is what the units pass, so
# it is the effective setting on a running machine; an install predating
# --time-stamping has no flag, and ptp4l's own default of hardware is what such
# an install was really running.
stamping_in_use() {
  local args
  args=" $(env_get PTP4L_ARGS || true) "
  case "$args" in
    *' -S '*) printf 'software\n' ;;
    *' -L '*) printf 'legacy\n' ;;
    *' -H '*) printf 'hardware\n' ;;
    *)        printf 'hardware\n' ;;
  esac
}

# The install record is the authority -- a wrong flag in the env file has to be
# detectable, which it would not be if the expected arguments were derived from
# that same file.
stamping_recorded() {
  local v
  v="$(state_get time_stamping || true)"
  # Older installs predate the record, so fall back to the flag the units are
  # actually started with -- but only on a machine that has one.  On a bare
  # machine there is no answer at all, and printing one (hardware, the ptp4l
  # default) would describe a deployment that does not exist.
  if [ -z "$v" ] && [ -n "$(env_get PTP4L_ARGS || true)" ]; then
    v="$(stamping_in_use)"
  fi
  printf '%s\n' "$v"
}

# Is this unit actually *present* on this machine?  Ask systemd for LoadState
# rather than `systemctl cat`: cat succeeds for a unit that exists only as a
# dangling enable symlink (an alias left by an earlier run, or by a package
# that was removed without disabling it), and such a unit must be treated as
# absent -- there is nothing to start, and enabling it would silently do
# nothing while `timesync` reported success.
have_unit() { [ "$(systemctl show -p LoadState --value "$1" 2>/dev/null)" = loaded ]; }

unit_state() {  # "active/enabled"; never fails
  local a e
  a="$(systemctl is-active "$1" 2>/dev/null || true)"
  e="$(systemctl is-enabled "$1" 2>/dev/null || true)"
  printf '%s/%s\n' "${a:-n/a}" "${e:-n/a}"
}

# Any enabled ptp4l@/phc2sys@ instance other than the configured one.  Two
# instances on one machine fight over the same clock, so this is a fault.
#
# The instances are found on the filesystem, not through systemctl.  Both of
# the obvious queries lie about template instances on systemd 249, verified on
# the target: `list-unit-files 'ptp4l@*.service'` matches the *template* and
# reports it as "indirect", and `list-unit-files --state=enabled` filters the
# instances away entirely -- so an enabled ptp4l@usb0.service was invisible and
# the second-instance fault went undetected.  Enabling an instance IS the act
# of creating a symlink under <target>.wants/, so that symlink is the ground
# truth, and it is what `systemctl disable` removes.
enabled_instances() {
  local t u p dir
  for t in ptp4l phc2sys; do
    for dir in "$(R /etc/systemd/system)" "$(R /run/systemd/system)"; do
      for p in "$dir"/*.wants/"$t"@*.service; do
        [ -L "$p" ] || continue
        u="$(basename "$p")"
        [ "$u" != "$t@$IFACE.service" ] || continue
        printf '%s\n' "$u"
      done
    done
  done | sort -u
}

# ---------------------------------------------------------------------------
# Writing files.  Each install_* helper prints exactly one line saying whether
# anything changed -- so a second run over an already-converged machine visibly
# does nothing, which is what makes this safe to drive from a production script.
#
# The content is staged into a file in the DESTINATION directory and then moved
# into place, so a half-written config can never be observed, and the move
# stays atomic within one filesystem.
#
# Note the deliberate shape: the staging file is created and recorded here, in
# the top-level shell, and the template function is the only thing running on
# the left of a pipe.  Anything that records its own temp file from inside a
# pipeline (or a command substitution) would be recording it in a subshell, and
# the cleanup on exit would never see it.
# ---------------------------------------------------------------------------
CHANGED=0
TMPPATH=""

new_tmp() {  # new_tmp DEST_PATH -> sets TMPPATH
  local path
  path="$(R "$1")"
  if [ "$DRY" = 1 ]; then
    TMPPATH="$(mktemp)"
  else
    mkdir -p "$(dirname "$path")"
    TMPPATH="$(mktemp "${path}.tmp.XXXXXX")"
  fi
  TMPFILES+=("$TMPPATH")
}

install_bytes() {  # install_bytes TMP_FILE DEST_PATH [MODE]
  local tmp="$1" label="$2" mode="${3:-0644}" path
  path="$(R "$label")"

  if [ -e "$path" ] && cmp -s "$tmp" "$path"; then
    say "unchanged $label"
    rm -f "$tmp"
    return 0
  fi

  CHANGED=1
  if [ "$DRY" = 1 ]; then
    say "would write $label"
    rm -f "$tmp"
    return 0
  fi

  chmod "$mode" "$tmp"
  if [ -z "$ROOT" ]; then
    chown root:root "$tmp"
  fi
  mv -f "$tmp" "$path"
  say "wrote     $label"
}

install_tpl() {  # install_tpl TPL_FUNCTION DEST_PATH [MODE]
  new_tmp "$2"
  local tmp="$TMPPATH"
  "$1" | render >"$tmp"
  install_bytes "$tmp" "$2" "${3:-0644}"
}

# Same, but several templates concatenated into ONE file.  ptp4l reads its
# settings from the file named by -f and DISCARDS any earlier file on the same
# command line, so a role that needs "shared settings, plus mine, plus the GNSS
# block" has to arrive as one file rather than three -f arguments.
install_tpl_join() {  # install_tpl_join DEST_PATH TPL_FUNCTION...
  local dest="$1"; shift
  new_tmp "$dest"
  local tmp="$TMPPATH" f
  : >"$tmp"
  for f in "$@"; do
    "$f" | render >>"$tmp"
  done
  install_bytes "$tmp" "$dest"
}

install_from_file() {  # install_from_file SRC_FILE DEST_PATH [MODE]
  new_tmp "$2"
  local tmp="$TMPPATH"
  cat "$1" >"$tmp"
  install_bytes "$tmp" "$2" "${3:-0644}"
}

install_marked_copy() {  # install_marked_copy SRC_FILE DEST_PATH [MODE]
  new_tmp "$2"
  local tmp="$TMPPATH"
  { printf '%s\n' "$MARK"; cat "$1"; } >"$tmp"
  install_bytes "$tmp" "$2" "${3:-0644}"
}

remove_generated() {  # remove_generated PATH [SIGNATURE]
  # Only removes a file this tool wrote.  The signature defaults to the marker
  # every generated file carries as its first line; the installed copy of this
  # script cannot carry it (a shebang has to come first), so it is identified by
  # a phrase from its own header instead.  A file the operator owns must never
  # be removed just because it mentions timesync somewhere inside.
  local path sig="${2:-^# generated by $NAME}"
  path="$(R "$1")"
  [ -e "$path" ] || { say "absent    $1"; return 0; }
  if ! grep -q "$sig" "$path"; then
    warn "$1 does not look like a file timesync wrote; leaving it alone"
    return 0
  fi
  CHANGED=1
  if [ "$DRY" = 1 ]; then
    say "would remove $1"
  else
    rm -f "$path"
    say "removed   $1"
  fi
}

write_state() {
  local path prev gq
  path="$(R "$STATE_FILE")"
  prev="$(state_get installed || true)"
  # gnss_quality records a capability of the machine, not of the current role,
  # so a `switch` to slave keeps it -- that is what lets `switch master` bring back
  # the grandmaster config without the operator re-typing the recipe flags.
  # Only KEEP_GNSS (set by do_switch) does this: a plain `install` is
  # a full re-provision, and there the operator's flags are authoritative.
  # The state file has to be read before it is overwritten, hence reading it
  # here rather than in the callers.
  gq="$ADVERTISE_GNSS"
  if [ "$KEEP_GNSS" = 1 ] && [ "$ROLE" != master ]; then
    gq="$(state_get gnss_quality || true)"
    gq="${gq:-0}"
  fi
  if [ "$DRY" = 1 ]; then
    say "would write $STATE_FILE"
    return 0
  fi
  mkdir -p "$(dirname "$path")"
  cat >"$path" <<EOF
$MARK
# What was installed, by which version.  Read by 'timesync status'.
tool_version=$VERSION
role=$ROLE
iface=$IFACE
domain=$DOMAIN
transport=$TRANSPORT
time_stamping=$TIME_STAMPING
gnss_quality=$gq
installed=${prev:-$(date -Is)}
switched=$(date -Is)
EOF
  chmod 0644 "$path"
