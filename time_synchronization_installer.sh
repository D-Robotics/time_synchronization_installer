# (NIC clock), -L legacy.
PTP4L_ARGS=@PTP4L_ARGS@

# phc2sys: -s is where time comes from, -c is where it is copied to.  The
# direction is what distinguishes the two roles.  Empty when the mode is
# software or legacy: ptp4l then stamps in CLOCK_REALTIME itself, so there is
# no second clock to carry time to or from and phc2sys is left disabled.
PHC2SYS_ARGS=@PHC2SYS_ARGS@
