tpl_ptp4l_unit() {
cat <<'PTPSVC_EOF'
@MARK@
# Replaces the packaged /lib/systemd/system/ptp4l@.service.
#
# A unit file under /etc/systemd/system shadows the packaged one entirely --
# systemd takes the first match on its search path and does not merge the two --
# which is what is needed here: the packaged unit hardcodes the packaged config
# path and has no Restart=.  Trade-off: changes to the packaged unit in a future
# linuxptp package update will NOT arrive.  This file is short, so diff it
# against /lib/systemd/system/ptp4l@.service after an upgrade if that matters.
#
# The config comes from PTP4L_ARGS in /etc/default/ptp4l, which
# `timesync install|switch` generates.  PTP4L_ARGS is written unbraced on
# purpose: systemd splits an unbraced variable into separate arguments, which
# is how both -f flags get through.  ${PTP4L_ARGS} would arrive as a single
# argument and ptp4l would reject it.
#
# The interface still comes from %I, so the unit stays instance-generic
# (ptp4l@eth0.service).
[Unit]
Description=Precision Time Protocol (PTP) service for %I
Documentation=man:ptp4l
After=sys-subsystem-net-devices-%i.device
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
EnvironmentFile=/etc/default/ptp4l
# The NIC's PHC only becomes openable once the driver has opened the MAC; before
# that /dev/ptp0 fails with "Operation not permitted" and ptp4l dies at startup.
# `After=sys-subsystem-net-devices-%i.device` does not cover it -- that device
# unit goes active the moment the netdev is registered, seconds before the MAC
# is up -- and `After=network-online.target` did not either, because the
# NetworkManager wait-online helper is not enabled on this image, so that target
# is reached at t=0.  Hence an explicit gate.  See `timesync wait-iface` in the
# tool for the boot measurements.  It waits on IFF_UP, so a cable that is not
# plugged in does not block the unit.
#
# The gate is kept in every time-stamping mode, not just hardware: in software
# mode there is no PHC to open, but ptp4l still binds a UDP socket to the
# interface, and starting before the interface is up fails the same way.
ExecStartPre=/usr/local/sbin/timesync wait-iface %I
ExecStart=/usr/sbin/ptp4l $PTP4L_ARGS -i %I

# The packaged unit has no Restart and only orders after the network *device*,
# which exists before the interface has an address.  With UDPv4 transport
# ptp4l binds a socket on the interface, so an address-less eth0 makes it exit
# -- and with no Restart the service would sit dead until someone noticed.
# A deliberate `systemctl stop` exits 0 and is not restarted.
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
PTPSVC_EOF
}

tpl_phc2sys_unit() {
cat <<'PTPSVC_EOF'
@MARK@
# Replaces the packaged /lib/systemd/system/phc2sys@.service, which is broken:
# it declares
#
#     Requires=ptp4l.service
#     After=ptp4l.service
#
# for a unit this package does not ship -- only the template ptp4l@.service
# exists.  Starting phc2sys@eth0 therefore fails outright with
# "Unit ptp4l.service not found".  The correct, instance-matched dependency is
# ptp4l@%i.service, which with phc2sys@eth0.service expands to ptp4l@eth0.
#
# This is a replacement rather than a drop-in override because an empty
# `Requires=` in a drop-in does NOT clear the packaged one -- verified with
# `systemctl show phc2sys@eth0.service -p Requires` on this systemd 249, which
# still listed ptp4l.service.  The packaged dependency directives do not
# document an empty-string reset, unlike Environment=/ExecStart=/Documentation=.
#
# Same trade-off as ptp4l@.service: this file shadows the packaged unit, so
# package updates to that unit will not arrive.
[Unit]
Description=Synchronize system clock or PTP hardware clock (PHC)
Documentation=man:phc2sys
Requires=ptp4l@%i.service
After=ptp4l@%i.service
Before=time-sync.target

[Service]
Type=simple
EnvironmentFile=/etc/default/ptp4l
# Same MAC-up gate as ptp4l@.service, and it is needed here for a reason that is
# easy to get wrong: -w does NOT protect phc2sys from this race.  -w waits for
# ptp4l to report a synchronized state, but phc2sys resolves `-s eth0` to
# /dev/ptp0 while parsing its options, before any waiting happens -- on the boot
# measured in that comment it died at t=12.56s with the same
# "cannot open /dev/ptp0 for eth0: Operation not permitted", printing its usage.
ExecStartPre=/usr/local/sbin/timesync wait-iface %I
# -w holds phc2sys back until ptp4l reports a synchronized state, so it stays
# dormant -- and touches no clock -- while the master is absent or unreachable.
# That is what keeps this safe to leave running before a master exists.
ExecStart=/usr/sbin/phc2sys -w $PHC2SYS_ARGS
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
PTPSVC_EOF
}

tpl_env_file() {
cat <<'PTPSVC_EOF'
@MARK@
# Role selector for this board's PTP setup.
#
# `timesync` is the only thing that should write this file:
#
#     sudo timesync slave      # follow a PTP master on the network
#     sudo timesync master     # serve this board's own (GNSS) time to the network
#     sudo timesync status     # what is running right now
#
# The two systemd units read the arguments below, which is why switching roles
# needs neither a unit edit nor any enable/disable churn.  The PTP settings
# themselves live in /etc/linuxptp/.
#
# The two roles are mutually exclusive.  This file describes exactly one of
# them, and that is the only role that can be active at a time.
# ---------------------------------------------------------------------------

PTP_ROLE=@ROLE@
PTP_IFACE=@IFACE@

# ptp4l: the role's config file, plus the time-stamping mode as a flag.  The
