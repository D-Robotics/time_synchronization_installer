# ---------------------------------------------------------------------------
say()  { printf '%s: %s\n' "$NAME" "$*"; }
note() { printf '          %s\n' "$*"; }
warn() { printf '%s: WARNING: %s\n' "$NAME" "$*" >&2; }
die()  { local code="$1"; shift; printf '%s: ERROR: %s\n' "$NAME" "$*" >&2; exit "$code"; }

# Announcing something that is about to be DONE on the machine.  Under
# --dry-run it says so instead of implying the change happened.
act() { if [ "$DRY" = 1 ]; then say "would $*"; else say "$*"; fi; }

cleanup() { local f; for f in ${TMPFILES[@]+"${TMPFILES[@]}"}; do rm -f "$f"; done; }
on_signal() { cleanup; exit 130; }
trap cleanup EXIT
trap on_signal INT TERM

# Every path this tool touches goes through R(), so that --root can stage the
# whole tree somewhere harmless and let a human read it before it is deployed.
R() { printf '%s' "${ROOT}${1}"; }

