#!/bin/bash
# ===========================================================================
# time_synchronization_installer -- deploy and switch the time-synchronization
# role of a D-Robotics X5 board.
#
# Source file: time_synchronization_installer.sh.  It installs itself as the
# shorter command `timesync` (that is the name to type in the field, and the
# name used throughout the messages below); the file and the repository keep
# the long name.
#
# Written for mass production.  A freshly flashed board gets ONE command that
# installs everything and puts it in the requested role; the same tool switches
# an already-provisioned board between the two roles.
#
# The two roles are MUTUALLY EXCLUSIVE -- a board is either a slave or a
# master, never both, and switching rewrites every layer that differs:
#
#   slave   timesync slave
#           ptp4l as a slave; chrony stopped and disabled, because it would
#           fight ptp4l over CLOCK_REALTIME (two control loops steering one
#           clock).
#           Result: this board follows a PTP master on the network.
#
#   master  timesync master
#           ptp4l as a master + chrony (disciplines CLOCK_REALTIME from GNSS).
#           Result: this board serves its GNSS-disciplined time to the
#           network's slaves.
#
# WHICH CLOCK ALL OF THAT IS ABOUT is decided separately, by the time-stamping
# mode (--time-stamping, default software):
#
#   software / legacy   ptp4l stamps in CLOCK_REALTIME, so it disciplines that
#                       clock itself and no PTP hardware clock is involved.
#                       One daemon per role.
#   hardware            ptp4l stamps in the NIC's own clock, so it disciplines
#                       that, and phc2sys carries the time between the two
#                       (PHC -> CLOCK_REALTIME as a slave, the reverse as a
#                       master).  Two daemons per role.
#
# The role therefore lives in ONE generated file, /etc/default/ptp4l, which
# both systemd units read -- so switching never edits a unit and never
# enables/disables the units themselves.
#
# ---------------------------------------------------------------------------
# WHAT IT INSTALLS (all generated files carry a "generated by timesync" marker)
#
#   /etc/linuxptp/ptp4l-slave.conf        the slave role, complete
#   /etc/linuxptp/ptp4l-master.conf       the master role, complete (including
#                                         the GNSS time quality, if configured)
#   /etc/systemd/system/ptp4l@.service    shadows the packaged unit
#   /etc/systemd/system/phc2sys@.service  shadows the packaged unit (installed
#                                         always, enabled only in hardware mode)
#   /etc/default/ptp4l                    the role: args + interface
#   /usr/local/sbin/timesync              this script, for field switching
#   /etc/chrony/conf.d/20-ptp-refclock.conf copy of --refclock-file (master)
#   /var/lib/timesync/state               what was installed, by which version
#   /var/lib/timesync/disabled-ntp-units  NTP units we turned off, to restore
#
# ONE CONFIG FILE PER ROLE, NOT A SHARED ONE PLUS A ROLE ONE
#   ptp4l merges -f files by DISCARDING the earlier ones: with
#   `-f a -f b`, a key that only `a` sets is not in effect -- measured on this
#   board with `pmc 'GET DEFAULT_DATA_SET'` (a domainNumber set in the first
#   file read back as 0 from the running daemon).  Keys within ONE file do
#   accumulate, including across two [global] sections.  So each role gets a
#   single self-contained file, because the alternative silently ignores
#   whatever lands in the discarded one.
#
# WHY THE UNITS ARE REPLACED RATHER THAN OVERRIDDEN
#   The packaged phc2sys@.service declares Requires=ptp4l.service, but the
#   linuxptp package ships no such unit -- only the template ptp4l@.service.
#   phc2sys@eth0 therefore fails outright with "Unit ptp4l.service not found".
#   A drop-in cannot fix it: an empty "Requires=" was verified NOT to clear the
#   packaged list on systemd 249 (unlike Documentation=/ExecStart=, which
#   systemd documents as resettable).  A file in /etc/systemd/system shadows
#   the packaged one entirely, which does work.  Trade-off: a future linuxptp
#   package update to those units will not arrive -- if that matters, diff them
#   against /lib/systemd/system/ after an upgrade.
#
# EXIT CODES (stable; a production line may branch on them)
#   0  success
#   1  usage error (bad flag, bad value, contradictory flags)
#   2  preflight failed -- nothing was changed
#   3  apply failed (a file could not be written, a unit would not restart)
#   4  verify failed -- the unit is NOT fit to ship
#   5  GPS unconfigured: master was requested without a validated GNSS recipe
#
# ---------------------------------------------------------------------------
# TYPICAL USE
#
#   # new machine, fresh flash -- the slave role, one command.  This is
#   # software time stamping (the default): no PTP hardware clock is involved,
#   # accuracy is NTP-grade, and it works on any interface:
#   sudo ./time_synchronization_installer.sh install slave
#
#   # ... and the same, but taking its timestamps from the NIC's own clock
#   # (only where the NIC and its driver really do hardware-stamp):
#   sudo ./time_synchronization_installer.sh install slave --time-stamping hardware
#
#   # new machine, the master role, with a GNSS recipe validated on a bench unit:
#   sudo ./time_synchronization_installer.sh install master \
#        --refclock-file ./gnss/refclock.conf --gps-device /dev/ttyS0 \
#        --advertise-gnss-quality
#
#   # an already-provisioned board, in the field:
#   sudo timesync slave          # or: sudo timesync switch slave
#   sudo timesync master         # or: sudo timesync switch master
#   sudo timesync status
#   sudo timesync verify         # ship gate: exit 4 or 5 means DO NOT SHIP
#
#   # rehearse without touching the machine, then inspect what would be written:
#   sudo ./time_synchronization_installer.sh --dry-run install slave
#   ./time_synchronization_installer.sh --root /tmp/stage install slave \
#        && find /tmp/stage -type f
#
#   (1 and 2 are still accepted wherever a role is expected -- see the
#    "shorthands" note in --help.  The words are the interface.)
# ===========================================================================

set -euo pipefail

VERSION=1.1.0

# The one place the tool's names live.  NAME is the command an operator types
# and the prefix on every message; SRCFILE is how this file refers to itself in
# usage examples.  A rename should only ever mean editing these two lines --
# they feed the marker on every generated file, the install path and the state
# directory, so a half-done rename would leave files the tool no longer
# recognises as its own.
NAME=timesync
