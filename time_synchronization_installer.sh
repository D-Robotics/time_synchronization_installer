write_install_files() {  # writes every generated file; sets RESTART_NEEDED
  CHANGED=0
  # One self-contained file per role -- shared settings, then the role's own,
  # then the GNSS quality lines when they apply.  All three fragments are
  # concatenated, and each keeps its own [global] header: keys accumulate
  # within one file, including across two [global] sections.
  install_tpl_join "$CONF_DIR/ptp4l-slave.conf" tpl_common_conf tpl_slave_conf
  if [ "$ROLE" = master ] && [ "$ADVERTISE_GNSS" = 1 ]; then
    install_tpl_join "$CONF_DIR/ptp4l-master.conf" tpl_common_conf tpl_master_conf tpl_grandmaster_conf
  else
    install_tpl_join "$CONF_DIR/ptp4l-master.conf" tpl_common_conf tpl_master_conf
  fi
  install_tpl tpl_ptp4l_unit   "$UNIT_DIR/ptp4l@.service"
  install_tpl tpl_phc2sys_unit "$UNIT_DIR/phc2sys@.service"

  # The two files an earlier version split this into.  Neither is named in
  # PTP4L_ARGS any more, so leaving them behind would leave settings on disk
  # that nothing reads -- the trap this layout exists to avoid.
  remove_generated "$CONF_DIR/ptp4l-common.conf"
  remove_generated "$CONF_DIR/ptp4l-grandmaster.conf"

  # Decided after every write, the GNSS lines included: they are part of the
  # file ptp4l reads, and only a restart makes systemd re-read the
  # EnvironmentFile, so deciding earlier would leave a daemon running with the
  # arguments it was started with while the file it reads has changed.
  if [ "$CHANGED" = 1 ]; then
    RESTART_NEEDED=1
  fi

  if [ -n "$REFCLOCK_FILE" ]; then
    # The marker line goes on top of the integrator's recipe, where chrony
    # treats it as a comment.  It is what makes ownership of the file -- and so
    # its removal on uninstall -- unambiguous.
    install_marked_copy "$REFCLOCK_FILE" "$REFCLOCK_DEST"
  elif [ "$KEEP_GNSS" != 1 ]; then
    # No recipe given and this is not a switch, so it is a full re-provision to
    # a role that does not consume GNSS: drop a recipe left over from an
    # earlier GNSS install, so what is on disk describes this board's actual
    # wiring.  A `switch` deliberately keeps it -- switching back to master
    # has to find the recipe still there.
    remove_generated "$REFCLOCK_DEST"
  fi

  local self
  self="$(readlink -f "${BASH_SOURCE[0]}" 2>/dev/null || true)"
  if [ -n "$self" ] && [ -r "$self" ]; then
    install_from_file "$self" "$TOOL_DEST" 0755
  else
    warn "cannot resolve my own path; skipping the install of $TOOL_DEST"
  fi
  return 0
}

daemon_reload_if_needed() {
  if [ "$DRY" = 1 ]; then
    say "would run systemctl daemon-reload"
    return 0
  fi
  systemctl daemon-reload
}

do_install() {
  local role_arg="$1"

  ROLE_ARG="$role_arg"

  if [ -z "$ROOT" ]; then
    apt_ensure            # first: interface detection needs ethtool
  else
    say "--root $ROOT: staging only; apt, systemctl and hardware checks are skipped"
  fi

  resolve_iface
  role_values "$role_arg"
  preflight_args
  if [ -z "$ROOT" ]; then
    preflight_machine
  fi

  say "installing role $ROLE on $IFACE"
  write_install_files

  if [ -n "$ROOT" ]; then
    install_tpl tpl_env_file "$ENV_FILE"
    write_state
    printf '\n'
    say "staged under $ROOT; nothing on this machine was changed"
    return 0
  fi

  if [ "$RESTART_NEEDED" = 1 ]; then
    daemon_reload_if_needed
  fi

  role_values "$role_arg"
  apply_role
  write_state

  if [ "$DRY" = 1 ]; then
    printf '\n'
    say "dry run: nothing was changed, so there is nothing to verify"
    return 0
  fi

  if [ "$NO_VERIFY" = 1 ]; then
    printf '\n'
    warn "--no-verify was given: the apply steps ran, but this unit has NOT been checked"
    return 0
  fi

  printf '\n'
  do_verify "$role_arg"
}

do_switch() {
  local role_arg="$1"

  if [ ! -r "$ENV_FILE" ] || [ ! -r "$TOOL_DEST" ] \
     || [ ! -r "$UNIT_DIR/ptp4l@.service" ] || [ ! -r "$CONF_DIR/ptp4l-slave.conf" ]; then
    die 2 "this machine has not been provisioned yet -- run 'timesync install slave' (or 'install master') first"
  fi

  ROLE_ARG="$role_arg"
  KEEP_GNSS=1

  # A switch changes the ROLE and nothing else.  Everything else the machine
  # was already doing -- the interface it runs on, the transport and domain it
  # was installed with, whether it advertises GNSS quality -- carries over
  # unless it is given explicitly.  Switching must never quietly reset the
  # domain or demote a GNSS grandmaster to a skeleton.
  #
  # GNSS quality is the exception: it is a master-only attribute, and carrying
  # it into slave makes preflight_args reject the very switch back to slave
  # ("--advertise-gnss-quality is master only"), which would strand a board that
  # was serving GNSS.  So it is carried forward only when the target role is
  # master; the intent survives in the state file either way, and the next
  # switch to master picks it up again.
  local prev
  case "$role_arg" in
    master)
      if [ "$ADVERTISE_SET" != 1 ]; then
        prev="$(state_get gnss_quality || true)"
        if [ "${prev:-0}" = 1 ]; then
          ADVERTISE_GNSS=1
          note "keeping GNSS time-quality advertising from the existing install"
        fi
      fi
      ;;
  esac
  if [ "$DOMAIN_SET" != 1 ]; then
    prev="$(state_get domain || true)"
    if [ -n "$prev" ] && [ "$prev" != "$DOMAIN" ]; then
      DOMAIN="$prev"
      note "keeping PTP domain $DOMAIN from the existing install"
    fi
  fi
  if [ "$TRANSPORT_SET" != 1 ]; then
    prev="$(state_get transport || true)"
    if [ -n "$prev" ] && [ "$prev" != "$TRANSPORT" ]; then
      TRANSPORT="$prev"
      note "keeping transport $TRANSPORT from the existing install"
    fi
  fi
  # Time stamping carries over like the rest, and it decides which units the
  # new role needs -- so it has to be settled before role_values() is called.
  if [ "$TIME_STAMPING_SET" != 1 ]; then
    prev="$(stamping_recorded)"
    if [ -n "$prev" ] && [ "$prev" != "$TIME_STAMPING" ]; then
      TIME_STAMPING="$prev"
      note "keeping time stamping $TIME_STAMPING from the existing install"
    fi
  fi

  resolve_iface
  role_values "$role_arg"
  preflight_args
  preflight_machine

  # The role-dependent config files have to be (re)written here, not only by
  # `install`.  Switching to a GNSS master adds the clockClass/clockAccuracy
  # lines to the master file, and switching away removes them -- a board left
  # advertising GNSS quality it is no longer fed would be lying to every slave.
  # This also makes --domain/--transport on a switch actually take effect, and
  # keeps the unit files honest if one of them was edited by hand.  Everything
  # already correct reports "unchanged".
  write_install_files
  if [ "$RESTART_NEEDED" = 1 ]; then
    daemon_reload_if_needed
  fi
  role_values "$role_arg"      # write_install_files may have moved the target

  apply_role
  write_state

  if [ "$DRY" = 1 ]; then
    printf '\n'
    say "dry run: nothing was changed, so there is nothing to verify"
    return 0
  fi

  if [ "$NO_VERIFY" = 1 ]; then
    return 0
  fi
  printf '\n'
  do_verify "$role_arg"
}

do_uninstall() {
  local u found

  if [ -n "$ROOT" ]; then
    say "--root $ROOT: removing only the staged tree; systemd is not touched"
  else
    [ "$(id -u)" -eq 0 ] || die 2 "must run as root (try: sudo $0 uninstall)"
    # IFACE, not a local: enabled_instances() excludes the configured instance
    # by comparing against $IFACE, so leaving it empty here made the two real
    # units look like strays and reported each of them twice.
    IFACE="$(env_get PTP_IFACE || true)"
    IFACE="${IFACE:-$DEFAULT_IFACE}"
    found="$(enabled_instances | tr '\n' ' ')"
    if [ "$DRY" = 1 ]; then
      for u in "ptp4l@${IFACE}.service" "phc2sys@${IFACE}.service" $found; do
        say "would stop and disable $u"
      done
    else
      # The configured units may not be there to begin with (never installed,
      # or a previous uninstall already removed them).  The strays in $found
      # are enable symlinks by construction, so those are removed even when the
      # template behind them has been deleted -- a dangling symlink is exactly
      # the leftover this tool exists to clean up.
      for u in "ptp4l@${IFACE}.service" "phc2sys@${IFACE}.service"; do
        have_unit "$u" || continue
        act "stop and disable $u"
        systemctl disable --now "$u" >/dev/null 2>&1 || true
      done
      for u in $found; do
        act "stop and disable $u"
        systemctl disable --now "$u" >/dev/null 2>&1 || true
      done
    fi
  fi

  remove_generated "$UNIT_DIR/ptp4l@.service"
  remove_generated "$UNIT_DIR/phc2sys@.service"
  remove_generated "$CONF_DIR/ptp4l-common.conf"
  remove_generated "$CONF_DIR/ptp4l-slave.conf"
  remove_generated "$CONF_DIR/ptp4l-master.conf"
  remove_generated "$CONF_DIR/ptp4l-grandmaster.conf"
  remove_generated "$ENV_FILE"
  remove_generated "$REFCLOCK_DEST"
  # The installed copy of this script leads with a shebang, so it cannot also
  # lead with the marker; it is recognised by a phrase from its own header.
  remove_generated "$TOOL_DEST" 'time_synchronization_installer -- deploy and switch'
  remove_generated "$STATE_FILE"

  # Put back whatever clock daemon this installation turned off.
  local path
  path="$(R "$DISABLED_NTP_FILE")"
  if [ -s "$path" ]; then
    while read -r u; do
      case "$u" in '' | '#'*) continue ;; esac
      say "re-enabling $u (it was enabled before this install)"
      if [ "$DRY" != 1 ]; then systemctl enable --now "$u" >/dev/null 2>&1 || true; fi
    done <"$path"
  fi
  remove_generated "$DISABLED_NTP_FILE"
  if [ "$DRY" != 1 ]; then rmdir "$(R "$STATE_DIR")" 2>/dev/null || true; fi

  if [ "$DRY" != 1 ] && [ -z "$ROOT" ]; then
    systemctl daemon-reload
  fi

  printf '\n'
  say "uninstalled -- the linuxptp package itself is untouched"
  note "the units that ship in /lib/systemd/system/ are in effect again"
}

# ===========================================================================
# Argument parsing
# ===========================================================================
while [ $# -gt 0 ]; do
  case "$1" in
    install|switch|uninstall)
      [ -z "$CMD" ] || die 1 "more than one command given ('$CMD' and '$1')"
      CMD="$1"; shift ;;
    status|verify)
      [ -z "$CMD" ] || die 1 "more than one command given ('$CMD' and '$1')"
      CMD="$1"; shift ;;
    slave|master)
      # `slave` and `master` are the way to spell the role, and what the word
      # means depends on what came before it: after a command that takes a role
      # it IS that role (`install slave`), while on its own it is the `switch`
      # shorthand (`timesync master` == `timesync switch master`).
      case "$CMD" in
        install|switch|verify)
          [ -z "$ROLE_ARG" ] || die 1 "role given twice ('$ROLE_ARG' and '$1')"
          ROLE_ARG="$1"; shift ;;
        "")
          CMD="$1"; shift ;;
        *)
          die 1 "'$CMD' does not take a role" ;;
      esac ;;
    wait-iface)
      [ -z "$CMD" ] || die 1 "more than one command given ('$CMD' and '$1')"
      [ $# -ge 2 ] || die 1 "wait-iface needs an interface name (usage: $NAME wait-iface <iface> [seconds])"
      # This command takes a positional argument, so a mistyped option would be
      # swallowed as the interface name and then wait uselessly for 30s.
      case "$2" in
        -*) die 1 "wait-iface: '$2' looks like an option; usage: $NAME wait-iface <iface> [seconds]" ;;
      esac
      CMD="$1"; WAIT_IFACE="$2"
      # Optional third word is the timeout in seconds.
      if [ $# -ge 3 ]; then
        case "$3" in
          '' | *[!0-9]*) die 1 "wait-iface: timeout must be a whole number of seconds, got '$3'" ;;
        esac
        WAIT_TIMEOUT="$3"; shift 3
      else
        shift 2
      fi ;;
    1|2)
      # Kept as shorthands for `slave` and `master`.  Digits never stand in for
      # a command, though: `timesync 1` was refused before this, and quietly
      # turning it into a state-changing switch is a worse answer to a typo
      # than refusing is.
      [ -z "$ROLE_ARG" ] || die 1 "role given twice ('$ROLE_ARG' and '$1')"
      # Normalised before anything can report an error, so that every message --
      # including the refusals just below -- prints the word rather than the
      # digit.  The digit is the spelling people found hard to follow.
      case "$1" in 1) ROLE_ARG=slave ;; 2) ROLE_ARG=master ;; esac
      case "$CMD" in
        install|switch|verify) ;;
        "") die 1 "role '$ROLE_ARG' needs a command: install $ROLE_ARG | switch $ROLE_ARG" ;;
        *)  die 1 "'$CMD' does not take a role" ;;
      esac
      shift ;;
    [0-9]*)
      die 1 "unknown role '$1' (want: slave | master, or 1 | 2)" ;;
    --iface)         [ $# -ge 2 ] || die 1 "--iface needs a value"; IFACE_OPT="$2"; shift 2 ;;
    --domain)        [ $# -ge 2 ] || die 1 "--domain needs a value"; DOMAIN="$2"; DOMAIN_SET=1; shift 2 ;;
    --transport)     [ $# -ge 2 ] || die 1 "--transport needs a value"; TRANSPORT="$2"; TRANSPORT_SET=1; shift 2 ;;
    --time-stamping) [ $# -ge 2 ] || die 1 "--time-stamping needs a value (software | hardware | legacy)"; TIME_STAMPING="$2"; TIME_STAMPING_SET=1; shift 2 ;;
    --refclock-file) [ $# -ge 2 ] || die 1 "--refclock-file needs a value"; REFCLOCK_FILE="$2"; shift 2 ;;
    --gps-device)    [ $# -ge 2 ] || die 1 "--gps-device needs a value"; GPS_DEVICE="$2"; shift 2 ;;
    --root)          [ $# -ge 2 ] || die 1 "--root needs a value"; ROOT="${2%/}"; shift 2 ;;
    --advertise-gnss-quality) ADVERTISE_GNSS=1; ADVERTISE_SET=1; shift ;;
    --no-apt)        NO_APT=1; shift ;;
    --no-verify)     NO_VERIFY=1; shift ;;
    --force)         FORCE=1; shift ;;
    --dry-run)       DRY=1; shift ;;
    -h|--help)       usage; exit 0 ;;
    -V|--version)    printf 'timesync %s\n' "$VERSION"; exit 0 ;;
    --)              shift; break ;;
    *)               usage; die 1 "unknown argument '$1'" ;;
  esac
done

case "$CMD" in
  install|switch)
    # ROLE_ARG is always the word by now -- the parser translates 1/2 on the
    # way in -- so there is no digit case to allow for here.
    case "$ROLE_ARG" in
      slave|master) ;;
      "") die 1 "$CMD needs a role: $CMD slave | $CMD master" ;;
      *)  die 1 "unknown role '$ROLE_ARG' (want: slave | master)" ;;
    esac
    if [ -n "$ROOT" ] && [ "$CMD" = switch ]; then
      die 1 "--root is for install and uninstall only; switch changes a live machine"
    fi
    ;;
  verify)
    if [ -n "$ROOT" ]; then
      die 1 "--root is for install and uninstall only; verify inspects a live machine"
    fi
    ;;
esac

case "$CMD" in
  install)   do_install "$ROLE_ARG" ;;
  switch)    do_switch "$ROLE_ARG" ;;
  slave)     do_switch slave ;;
  master)    do_switch master ;;
  status)    do_status ;;
  verify)    do_verify "${ROLE_ARG:-}" ;;
  wait-iface) do_wait_iface "$WAIT_IFACE" "${WAIT_TIMEOUT:-30}" ;;
  uninstall) do_uninstall ;;
  *)         usage; exit 2 ;;
esac
